const { chromium } = require('playwright');
const assert = require('assert');
(async()=>{
 const browser=await chromium.launch({headless:true});
 const page=await browser.newPage({viewport:{width:390,height:844},deviceScaleFactor:1,isMobile:true,hasTouch:true});
 const errors=[]; page.on('console',m=>{if(m.type()==='error')errors.push(m.text());}); page.on('pageerror',e=>errors.push(e.message));
 await page.goto('http://127.0.0.1:4173/cnc/',{waitUntil:'networkidle'});
 await page.waitForTimeout(1400);
 assert(await page.locator('#view-dashboard.view.active').count(),'根网址必须稳定停在首页');
 const toolEntry=page.locator('#view-dashboard [data-route="calculator"]:visible').first();
 await toolEntry.scrollIntoViewIfNeeded();
 await toolEntry.click();
 await page.waitForSelector('#view-calculator.view.active');
 await page.locator('[data-tool-tab="tool-tab3"]').click();
 await page.waitForSelector('#tool-tab3.active');
 await page.waitForFunction(()=>window.CNC_INDUSTRIAL_DIAGNOSIS&&window.CNC_INDUSTRIAL_DIAGNOSIS.runCheck().passed);
 const items=page.locator('#tool-diagList .diag-item');
 assert((await items.count())>=20,'异常排查应展示至少20条');
 const first=items.first();
 const box=await first.boundingBox();
 assert(box&&box.width>330,'排查卡应为手机单列宽卡');
 const header=first.locator('.diag-item-header');
 const hbox=await header.boundingBox();
 assert(hbox&&hbox.height>=58,'排查卡点击区至少58px');
 assert.strictEqual(await header.getAttribute('role'),'button');
 assert.strictEqual(await header.getAttribute('aria-expanded'),'false');
 await header.press('Enter');
 await page.waitForTimeout(80);
 assert.strictEqual(await header.getAttribute('aria-expanded'),'true');
 assert(await first.locator('.diag-detail').isVisible(),'键盘应能展开排查详情');
 await page.locator('#tool-diagSearch').fill('震纹');
 await page.waitForTimeout(420);
 assert((await items.count())>=1,'搜索震纹应有结果');
 await page.locator('#tool-diagSearch').fill('完全不存在的问题');
 await page.waitForTimeout(420);
 assert((await page.locator('#tool-diagList .diag-item').count())===0,'无结果时不应保留旧卡片');
 assert((await page.locator('#tool-diagList').innerText()).includes('未找到匹配的问题'),'应显示明确空状态');
 assert.strictEqual(errors.length,0,'控制台不应有错误: '+errors.join(' | '));
 console.log('mobile industrial diagnosis smoke passed');
 await browser.close();
})().catch(err=>{console.error(err);process.exit(1);});
